//! mx's electric instruments, fitted to recordings: the electric piano and the electric guitar.

use super::common::{Fitted, silent_after};
use crate::nodes::{clicks, db, hz, modes};
use crate::{Note, Spec, Synth};

/// Every synth of this family mx ships.
pub fn all() -> Vec<Synth> {
    vec![electric_piano()]
}

/// The bands the fitted figures are given at, in Hz, a third of an octave apart.
const BANDS: [f64; 22] = [
    40.0, 50.0, 63.0, 80.0, 101.0, 127.0, 160.0, 202.0, 254.0, 320.0, 403.0, 508.0, 640.0, 806.0,
    1016.0, 1280.0, 1613.0, 2032.0, 2560.0, 3225.0, 4064.0, 5120.0,
];
/// The recordings' velocities, 25, 50, 75, 100 and 127, as vel.
const VELS: [f64; 5] = [0.2, 0.39, 0.59, 0.79, 1.0];

fn electric_piano() -> Synth {
    Synth::new("electric_piano")
        .option(Spec::note("note").default(60.0).doc("The pitch."))
        .option(
            Spec::float("vel")
                .default(0.6)
                .range(0.0, 1.0)
                .doc("How hard the key is struck."),
        )
        .options(Spec::envelope(1000.0, 0.15))
        .build(|o, _ctx| {
            let vel = o.number("vel").clamp(0.0, 1.0);
            let freq = hz(o.number("note"));
            let (own, pitches, levels, fades) = EPIANO.harmonics(freq, vel);
            // The tine's bell: partials a third of a harmonic off the whole multiples, which ring shorter the higher the note and fade out above F4.
            let bell: Vec<(f64, f64)> = BELL
                .iter()
                .map(|(ratio, level, fall)| {
                    (freq * ratio, level - fall * (freq / 41.2).log2().max(0.0))
                })
                .filter(|(f, _)| *f < 7000.0)
                .collect();
            let bell_pitches: Vec<f64> = bell.iter().map(|(f, _)| *f).collect();
            let fall = 3.0 * (freq / 100.0).log2().max(0.0);
            let bell_levels: Vec<f64> = bell
                .iter()
                .map(|(_, level)| db(own + level - fall))
                .collect();
            let bell_fades = vec![(300.0 / freq).clamp(0.3, 8.0); bell.len()];
            let gain = 0.04 * vel.sqrt();
            let tine = modes(clicks(vec![(0.0, 1.0)]), &pitches, &levels, &fades)
                + modes(
                    clicks(vec![(0.0, 1.0)]),
                    &bell_pitches,
                    &bell_levels,
                    &bell_fades,
                );
            Note::envelope(tine * gain as f32, o).within(silent_after(&levels, &fades, gain))
        })
}

