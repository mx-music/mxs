//! mx's electric instruments, fitted to recordings: the electric piano and the electric guitar.

use super::common::{Fitted, silent_after};
use super::figures::Figures;
use crate::nodes::{clicks, db, hz, modes};
use crate::{Note, Spec, Synth};
use std::sync::OnceLock;

/// Every synth of this family mx ships.
pub fn all() -> Vec<Synth> {
    vec![electric_piano(), electric_guitar()]
}

/// The bands the fitted figures are given at, in Hz, a third of an octave apart.
const BANDS: [f64; 22] = [
    40.0, 50.0, 63.0, 80.0, 101.0, 127.0, 160.0, 202.0, 254.0, 320.0, 403.0, 508.0, 640.0, 806.0,
    1016.0, 1280.0, 1613.0, 2032.0, 2560.0, 3225.0, 4064.0, 5120.0,
];
/// The recordings' velocities, 25, 50, 75, 100 and 127, as vel.
const VELS: [f64; 5] = [0.2, 0.39, 0.59, 0.79, 1.0];

fn electric_piano() -> Synth {
    Synth::new("electric_piano")
        .option(Spec::note("note").default(60.0).doc("The pitch."))
        .option(
            Spec::float("vel")
                .default(0.6)
                .range(0.0, 1.0)
                .doc("How hard the key is struck."),
        )
        .options(Spec::envelope(1000.0, 0.15))
        .build(|o, _ctx| {
            let vel = o.number("vel").clamp(0.0, 1.0);
            let note = o.number("note");
            let figures = epiano();
            let voice = figures.voice(note, vel);
            // The recordings are each brought to the same peak, so a velocity carries the energy vel 1 has over the first half second, and plays louder by vel alone.
            let loudness = (figures.voice(note, 1.0).energy() / voice.energy()).sqrt();
            let gain = (EPIANO_LEVEL * vel.powf(0.4) * loudness).max(1e-9);
            let end = voice.silent_after();
            Note::envelope(voice.sound() * gain as f32, o).within(end)
        })
}

/// The electric piano's figures, fitted partial by partial to NSynth's keyboard_electronic_098.
fn epiano() -> &'static Figures {
    static FIGURES: OnceLock<Figures> = OnceLock::new();
    FIGURES.get_or_init(|| Figures::read(include_bytes!("figures/electric_piano.mxf")))
}

/// The electric piano's gain at vel 1, as loud at E3 as its alpha version.
const EPIANO_LEVEL: f64 = 0.168;

fn electric_guitar() -> Synth {
    Synth::new("electric_guitar")
        .option(Spec::note("note").default(52.0).doc("The pitch."))
        .option(
            Spec::float("vel")
                .default(0.6)
                .range(0.0, 1.0)
                .doc("How hard the string is picked."),
        )
        .options(Spec::envelope(1000.0, 0.08))
        .build(|o, _ctx| {
            let vel = o.number("vel").clamp(0.0, 1.0);
            let freq = hz(o.number("note"));
            let (_own, pitches, levels, fades) = EGUITAR.harmonics(freq, vel);
            // The pick: as it leaves the string, the harmonics from 1.2 kHz up ring for a moment, which the fades read over whole notes miss.
            let pick_pitches: Vec<f64> = (1..=200)
                .map(|n| freq * n as f64)
                .filter(|f| *f >= 1200.0 && *f < 7000.0)
                .collect();
            let loudest = levels.iter().cloned().fold(0.0, f64::max);
            let pick_levels: Vec<f64> = pick_pitches
                .iter()
                .map(|f| {
                    loudest * db(PICK + 20.0 * (vel - 1.0) - 15.0 * (f / 2000.0).log2().max(0.0))
                })
                .collect();
            let pick_fades = vec![0.3; pick_pitches.len()];
            let gain = 0.005 * vel.powf(0.4) * EGUITAR.loudness(freq, vel);
            let string = modes(clicks(vec![(0.0, 1.0)]), &pitches, &levels, &fades)
                + modes(
                    clicks(vec![(0.0, 1.0)]),
                    &pick_pitches,
                    &pick_levels,
                    &pick_fades,
                );
            Note::envelope(string * gain as f32, o).within(silent_after(&levels, &fades, gain))
        })
}

